const JA_TO_ZH = new Map(Object.entries(TAG_LABELS_JA_ZH));
const ZH_TO_JA = new Map<string, string[]>();
for (const [ja, zh] of JA_TO_ZH) {
  const list = ZH_TO_JA.get(zh);
  if (list) {
    list.push(ja);
  } else {
    ZH_TO_JA.set(zh, [ja]);
  }
}

export function localizeTag(tag: string): string {
  const value = tag.trim();
  if (!value) {
    return tag;
  }
  return JA_TO_ZH.get(value) ?? tag;
}

export function localizeTags(tags: string[]): string[] {
  const result: string[] = [];
  const seen = new Set<string>();
  for (const tag of tags) {
    const localized = localizeTag(tag);
    if (!localized || seen.has(localized)) {
      continue;
    }
    seen.add(localized);
    result.push(localized);
  }
  return result;
}

export function tagFilterVariants(tag: string): string[] {
  const value = tag.trim();
  if (!value) {
    return [];
  }
  const localized = localizeTag(value);
  const variants = new Set<string>([value, localized]);
  for (const ja of ZH_TO_JA.get(localized) ?? []) {
    variants.add(ja);
  }
  return [...variants];
}
